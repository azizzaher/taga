BEGIN;

CREATE TABLE IF NOT EXISTS public.food_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    food_name VARCHAR(120) NOT NULL,
    meal_type VARCHAR(16) NOT NULL
        CHECK (meal_type IN ('breakfast', 'lunch', 'dinner', 'snack')),
    serving VARCHAR(100) NOT NULL DEFAULT '1 serving',
    food_date DATE NOT NULL DEFAULT CURRENT_DATE,
    calories NUMERIC(8,2) NOT NULL CHECK (calories >= 0 AND calories <= 10000),
    protein_g NUMERIC(7,2) NOT NULL CHECK (protein_g >= 0 AND protein_g <= 1000),
    carbohydrates_g NUMERIC(7,2) NOT NULL CHECK (carbohydrates_g >= 0 AND carbohydrates_g <= 1000),
    fat_g NUMERIC(7,2) NOT NULL CHECK (fat_g >= 0 AND fat_g <= 1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS food_logs_user_date_created_idx
    ON public.food_logs (user_id, food_date, created_at DESC);

COMMIT;
